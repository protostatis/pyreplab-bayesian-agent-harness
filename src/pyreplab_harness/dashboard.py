def _parse_metrics(metrics_path: str | Path | None) -> dict[str, Any]:
    """Parse the optional outcome-model ``metrics.json`` into a safe bundle.

    Returns ``{"status": "present"|"missing"|"malformed", "warning", ...}``.
    Only whitelisted aggregate metric keys are kept; unknown keys (e.g. raw
    posterior samples) are dropped.  Binned calibration data is kept only when
    actually present in the file.
    """
    result: dict[str, Any] = {
        "status": "missing",
        "warning": None,
        "splits": [],
        "per_policy": [],
        "calibration": [],
        "has_calibration": False,
    }
    if metrics_path is None:
        return result
    path = Path(metrics_path).expanduser().resolve()
    if not path.is_file():
        result["warning"] = f"metrics file not found: {path}"
        return result
    try:
        with path.open("r", encoding="utf-8") as handle:
            raw = json.load(handle)
    except (json.JSONDecodeError, OSError) as error:
        result["status"] = "malformed"
        result["warning"] = f"metrics file unreadable: {error}"
        return result
    if not isinstance(raw, dict):
        result["status"] = "malformed"
        result["warning"] = "metrics JSON is not an object"
        return result

    split_names = [name for name in _SPLIT_ORDER if name in raw]
    split_names += sorted(name for name in raw if name not in _SPLIT_ORDER)
    split_names = [
        name
        for name in split_names
        if name != "calibration" and isinstance(raw.get(name), dict)
    ]
    if not split_names:
        result["status"] = "malformed"
        result["warning"] = "metrics JSON has no recognized split bundles"
        return result

    per_policy: list[dict[str, Any]] = []
    splits: list[dict[str, Any]] = []
    for name in split_names:
        bundle = raw[name]
        split_entry: dict[str, Any] = {"split": name}
        for key in ("n", *_MODEL_METRIC_KEYS):
            value = _finite_float(bundle.get(key))
            if key == "n":
                split_entry[key] = int(value) if value is not None else 0
            else:
                split_entry[key] = value
        splits.append(split_entry)
        policies = bundle.get("per_policy")
        if isinstance(policies, dict):
            for policy_id in sorted(policies):
                sub = policies[policy_id]
                if not isinstance(sub, dict):
                    continue
                entry: dict[str, Any] = {"split": name, "policy": policy_id}
                for key in ("n", *_MODEL_METRIC_KEYS):
                    value = _finite_float(sub.get(key))
                    if key == "n":
                        entry[key] = int(value) if value is not None else 0
                    else:
                        entry[key] = value
                per_policy.append(entry)

    result["splits"] = splits
    result["per_policy"] = per_policy
    result["calibration"] = _parse_calibration(raw.get("calibration"))
    result["has_calibration"] = any(bins["bins"] for bins in result["calibration"])
    result["status"] = "present"
    return result


def _parse_calibration(value: Any) -> list[dict[str, Any]]:
    """Normalize optional binned calibration data, or return ``[]``.

    Accepted shapes (only when real binned data exists):
    * ``{"train": [bin, ...], ...}`` keyed by split
    * ``[bin, ...]`` global bins
    * ``[{"split": "...", "confidence": .., "accuracy": .., "count": ..}, ...]``
    Each bin needs finite ``confidence``/``accuracy`` in ``[0, 1]`` and a
    non-negative integer ``count``; anything else is dropped, so aggregate
    metrics can never be fabricated into a calibration curve.
    """
    if value is None:
        return []

    def _clean_bin(bin_value: Any) -> dict[str, Any] | None:
        if not isinstance(bin_value, dict):
            return None
        confidence = _finite_float(bin_value.get("confidence"))
        accuracy = _finite_float(bin_value.get("accuracy"))
        count = _i(bin_value.get("count"))
        if confidence is None or accuracy is None:
            return None
        if not (0.0 <= confidence <= 1.0 and 0.0 <= accuracy <= 1.0):
            return None
        return {
            "lower": _finite_float(bin_value.get("lower")),
            "upper": _finite_float(bin_value.get("upper")),
            "confidence": confidence,
            "accuracy": accuracy,
            "count": max(count, 0),
        }

    result: list[dict[str, Any]] = []
    if isinstance(value, dict):
        for split in sorted(value):
            bins_value = value[split]
            if isinstance(bins_value, list):
                bins = [b for b in (_clean_bin(b) for b in bins_value) if b is not None]
                if bins:
                    result.append({"split": split, "bins": bins})
    elif isinstance(value, list):
        grouped: dict[str, list[dict[str, Any]]] = {}
        global_bins: list[dict[str, Any]] = []
        for bin_value in value:
            cleaned = _clean_bin(bin_value)
            if cleaned is None:
                continue
            split = bin_value.get("split")
            if isinstance(split, str) and split:
                grouped.setdefault(split, []).append(cleaned)
            else:
                global_bins.append(cleaned)
        for split in sorted(grouped):
            result.append({"split": split, "bins": grouped[split]})
        if global_bins:
            result.append({"split": "all", "bins": global_bins})
    return result


def _baseline_number(bundle: dict[str, Any], aliases: Iterable[str]) -> float | None:
    for key in aliases:
        value = _finite_float(bundle.get(key))
        if value is not None:
            return value
    return None


def _parse_baselines(baselines_path: str | Path | None) -> dict[str, Any]:
    """Parse the optional allocator baseline JSON into a safe strategy table."""
    result: dict[str, Any] = {
        "status": "missing",
        "warning": None,
        "rows": [],
    }
    if baselines_path is None:
        return result
    path = Path(baselines_path).expanduser().resolve()
    if not path.is_file():
        result["warning"] = f"baselines file not found: {path}"
        return result
    try:
        with path.open("r", encoding="utf-8") as handle:
            raw = json.load(handle)
    except (json.JSONDecodeError, OSError) as error:
        result["status"] = "malformed"
        result["warning"] = f"baselines file unreadable: {error}"
        return result

    entries: list[tuple[str, dict[str, Any]]] = []
    if isinstance(raw, dict) and "strategies" in raw and isinstance(raw["strategies"], (dict, list)):
        raw = raw["strategies"]
    if isinstance(raw, dict):
        for name in sorted(raw):
            bundle = raw[name]
            if isinstance(bundle, dict):
                entries.append((str(name), bundle))
    elif isinstance(raw, list):
        for item in raw:
            if isinstance(item, dict):
                name = item.get("strategy") or item.get("name")
                if isinstance(name, str) and name:
                    entries.append((name, item))
    if not entries:
        result["status"] = "malformed"
        result["warning"] = "baselines JSON contains no usable strategy rows"
        return result

    rows: list[dict[str, Any]] = []
    for name, bundle in entries:
        success = _baseline_number(bundle, _BASELINE_SUCCESS_ALIASES)
        if success is not None and success > 1.0:
            # Accept percentage-style values (73.2 -> 0.732).
            success = success / 100.0
        n_value = _baseline_number(bundle, _BASELINE_N_ALIASES)
        rows.append(
            {
                "strategy": name,
                "success_rate": success,
                "n": int(n_value) if n_value is not None else None,
                "mean_tokens": _baseline_number(bundle, _BASELINE_TOKENS_ALIASES),
                "mean_tool_calls": _baseline_number(bundle, _BASELINE_TOOLS_ALIASES),
                "mean_messages": _baseline_number(bundle, _BASELINE_MSGS_ALIASES),
            }
        )
    result["status"] = "present"
    result["rows"] = rows
    return result


