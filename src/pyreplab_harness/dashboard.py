def _render_bins_table(bins: list[dict[str, Any]]) -> str:
    headers = (
        "<tr><th scope=\"col\">Bin</th><th scope=\"col\">Range</th>"
        "<th scope=\"col\">Confidence</th><th scope=\"col\">Accuracy</th>"
        "<th scope=\"col\">Count</th></tr>"
    )
    parts = []
    for index, bin_value in enumerate(bins):
        low = bin_value.get("lower")
        high = bin_value.get("upper")
        if low is None and high is None:
            range_text = "—"
        else:
            range_text = f"[{_fmt_num(low, 3)} – {_fmt_num(high, 3)})"
        parts.append(
            f'<tr><td>{index + 1}</td><td>{range_text}</td>'
            f'<td>{_fmt_num(bin_value.get("confidence"), 3)}</td>'
            f'<td>{_fmt_num(bin_value.get("accuracy"), 3)}</td>'
            f'<td>{bin_value.get("count", 0)}</td></tr>'
        )
    return (
        '<div class="table-scroll"><table class="data">'
        f"<thead>{headers}</thead><tbody>{''.join(parts)}</tbody></table></div>"
    )


