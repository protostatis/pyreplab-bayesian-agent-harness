def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="pyreplab-harness-dashboard",
        description=(
            "Render a standalone static HTML dashboard for a pyreplab run "
            "(leakage-safe dataset + optional outcome-model metrics + optional "
            "allocator baselines)."
        ),
    )
    parser.add_argument("dataset", help="leakage-safe deterministic JSONL dataset")
    parser.add_argument("output", help="output standalone HTML path")
    parser.add_argument("--metrics", help="optional outcome-model metrics.json")
    parser.add_argument("--baselines", help="optional allocator baseline JSON")
    parser.add_argument("--title", help="dashboard title")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        summary = write_dashboard(
            args.dataset,
            args.output,
            metrics_path=args.metrics,
            baselines_path=args.baselines,
            title=args.title,
        )
    except (FileNotFoundError, ValueError, OSError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    print(json.dumps(summary, indent=2, sort_keys=True, ensure_ascii=False))
    return 0


