def build_dashboard_data(
    dataset_path: str | Path,
    metrics_path: str | Path | None = None,
    baselines_path: str | Path | None = None,
    *,
    title: str | None = None,
) -> dict[str, Any]:
    """Assemble every piece of dashboard data from the three input sources.

    The returned dict is JSON-serializable and self-contained: it carries the
    sanitized public rows (all of them, so the browser-side filters can
    recompute every section), the precomputed *unfiltered* aggregates used for
    the static markup, and the normalized optional inputs.
    """
    dataset = Path(dataset_path).expanduser().resolve()
    rows, skipped = _load_dataset_rows(dataset)
    public_rows = [_row_to_public(row) for row in rows]
    public_rows.sort(key=lambda row: (row["task_id"] or "", row["policy_id"] or "", row["attempt_id"] or ""))

    warnings: list[str] = []
    if skipped:
        warnings.append(f"{skipped} dataset row(s) skipped: missing identity or label keys")
    model = _parse_metrics(metrics_path)
    baselines = _parse_baselines(baselines_path)
    if model["warning"]:
        warnings.append(model["warning"])
    if baselines["warning"]:
        warnings.append(baselines["warning"])

    filters = {
        "family": sorted({row["family"] for row in public_rows}),
        "difficulty": sorted({row["difficulty"] for row in public_rows}),
        "policy": sorted({row["policy_id"] for row in public_rows}),
    }
    meta = {
        "title": title or "Pyreplab Harness Dashboard",
        # Only file basenames are embedded; absolute paths (which can carry a
        # username or host layout) never reach the HTML or the DATA payload.
        "dataset_basename": dataset.name,
        "metrics_basename": Path(metrics_path).expanduser().resolve().name if metrics_path else None,
        "baselines_basename": Path(baselines_path).expanduser().resolve().name if baselines_path else None,
        "rows": len(public_rows),
        "model_status": model["status"],
        "baselines_status": baselines["status"],
        "warnings": warnings,
    }
    return {
        "meta": meta,
        "filters": filters,
        "rows": public_rows,
        "gym": aggregate_gym(public_rows),
        "disagreement": policy_disagreement(public_rows),
        "failures": failure_analysis(public_rows),
        "costs": cost_stats(public_rows),
        "model": model,
        "baselines": baselines,
        "config": {
            "browser_cap": BROWSER_ROW_CAP,
            "prompt_preview_limit": PROMPT_PREVIEW_LIMIT,
        },
    }


