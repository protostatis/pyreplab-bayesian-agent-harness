def _render_banner(meta: dict[str, Any]) -> str:
    """Small-sample warning banner for datasets with fewer than 30 attempts."""
    rows = int(meta.get("rows") or 0)
    if 0 < rows < _SMALL_SAMPLE_THRESHOLD:
        return (
            f'<p class="banner" role="status">⚠ Small sample — only {rows} verified '
            f"attempts; aggregate statistics may be unstable.</p>"
        )
    return ""


def render_dashboard(data: dict[str, Any]) -> str:
    """Render ``data`` (from :func:`build_dashboard_data`) into a standalone HTML string."""
    meta = data.get("meta") or {}
    gym = data.get("gym") or {}
    disagreement = data.get("disagreement") or {}
    failures = data.get("failures") or {}
    costs = data.get("costs") or {}
    model = data.get("model") or {}
    baselines = data.get("baselines") or {}
    filters = data.get("filters") or {}
    config = data.get("config") or {}
    cap = int(config.get("browser_cap", BROWSER_ROW_CAP))

    header = _render_header(meta)
    banner = _render_banner(meta)
    filter_bar = _render_filters(filters)
    gym_html = _render_gym(gym)
    disagreement_html = _render_disagreement(disagreement)
    failures_html = _render_failures(failures)
    costs_html = _render_costs(costs)
    model_html = _render_model(model)
    baselines_html = _render_baselines(baselines)
    browser_html = _render_browser(data.get("rows") or [], cap)
    payload = _json_script_safe(data)

    return _TEMPLATE.replace("__HEADER__", header).replace(
        "__BANNER__", banner
    ).replace("__FILTERS__", filter_bar).replace("__GYM__", gym_html).replace(
        "__DISAGREEMENT__", disagreement_html
    ).replace("__FAILURES__", failures_html).replace(
        "__COSTS__", costs_html
    ).replace("__MODEL__", model_html).replace(
        "__BASELINES__", baselines_html
    ).replace("__BROWSER__", browser_html).replace(
        "__DATA_JSON__", payload
    )


def write_dashboard(
    dataset_path: str | Path,
    output_path: str | Path,
    metrics_path: str | Path | None = None,
    baselines_path: str | Path | None = None,
    *,
    title: str | None = None,
) -> dict[str, Any]:
    """Build and atomically write the standalone dashboard HTML.

    Returns a summary dict with the output path, byte size, row counts and
    model/baseline statuses.  The write is atomic (same-directory temp file +
    ``os.replace``), so a failed write never leaves a partial dashboard.
    """
    data = build_dashboard_data(dataset_path, metrics_path, baselines_path, title=title)
    html_doc = render_dashboard(data)
    target = Path(output_path).expanduser().resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        dir=target.parent,
        prefix=f".{target.name}.",
        delete=False,
    ) as handle:
        handle.write(html_doc)
        temporary = Path(handle.name)
    os.replace(temporary, target)
    return {
        "output_path": str(target),
        "bytes": len(html_doc.encode("utf-8")),
        "rows": data["meta"]["rows"],
        "model_status": data["meta"]["model_status"],
        "baselines_status": data["meta"]["baselines_status"],
        "warnings": data["meta"]["warnings"],
    }


