# ---------------------------------------------------------------------------
# Small coercion / formatting helpers
# ---------------------------------------------------------------------------
def _s(value: Any) -> str | None:
    return None if value is None else str(value)


def _i(value: Any) -> int:
    if isinstance(value, bool):
        return 0
    if isinstance(value, int):
        return value
    if isinstance(value, float) and math.isfinite(value):
        return int(value)
    return 0


def _finite_float(value: Any) -> float | None:
    if value is None or isinstance(value, bool):
        return None
    if isinstance(value, (int, float)):
        value = float(value)
        return value if math.isfinite(value) else None
    return None


def _preview(value: Any) -> str | None:
    """Sanitized prompt preview, whitespace-collapsed, capped at 120 chars."""
    if value is None:
        return None
    collapsed = " ".join(str(value).split())
    if len(collapsed) > PROMPT_PREVIEW_LIMIT:
        return collapsed[:PROMPT_PREVIEW_LIMIT] + "…"
    return collapsed or None


def _esc(value: Any) -> str:
    """HTML-escape an untrusted value for static markup."""
    return html.escape("" if value is None else str(value), quote=True)


def _fmt_pct(rate: float | None) -> str:
    return "—" if rate is None else f"{rate * 100:.1f}%"


def _fmt_num(value: float | None, digits: int = 1) -> str:
    return "—" if value is None else f"{value:.{digits}f}"


def _fmt_int(value: float | None) -> str:
    return "—" if value is None else f"{value:.0f}"


def _mean(values: list[float]) -> float | None:
    return sum(values) / len(values) if values else None


def _pop_std(values: list[float]) -> float | None:
    n = len(values)
    if n == 0:
        return None
    if n == 1:
        return 0.0
    mean = sum(values) / n
    return math.sqrt(sum((v - mean) ** 2 for v in values) / n)


def _min_max(values: list[float]) -> tuple[float | None, float | None]:
    if not values:
        return None, None
    return min(values), max(values)


def _json_script_safe(value: Any) -> str:
    """Serialize ``value`` so it is safe inside a ``<script>`` element.

    ``ensure_ascii=True`` already escapes every non-ASCII character; the extra
    replaces neutralise the three ASCII characters that can terminate or
    corrupt the script element even inside a string literal.
    """
    payload = json.dumps(value, ensure_ascii=True, sort_keys=True)
    return (
        payload.replace("<", "\\u003c")
        .replace(">", "\\u003e")
        .replace("&", "\\u0026")
    )


