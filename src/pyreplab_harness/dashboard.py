"""Standalone static HTML dashboard for a pyreplab experiment run.

The dashboard turns three optional sources into a single self-contained HTML
file (all CSS/JS/data embedded, no network, no CDN, no framework):

* ``dataset_path``   -- the leakage-safe deterministic JSONL corpus produced
  by :mod:`pyreplab_harness.dataset` (required input).
* ``metrics_path``   -- optional ``metrics.json`` emitted by
  :mod:`pyreplab_harness.outcome_model` (per-split metric bundles, optional
  binned calibration data).
* ``baselines_path`` -- optional allocator baseline JSON (strategy aggregate
  table).

Public API
----------
``build_dashboard_data(dataset_path, metrics_path=None, baselines_path=None)``
  -> dict  (all embedded data plus precomputed unfiltered aggregates)
``render_dashboard(data)``
  -> str   (the complete standalone HTML document)
``write_dashboard(...)``
  -> summary dict (atomic temp-file + replace write)
plus a module CLI (``python -m pyreplab_harness.dashboard``).

Privacy whitelist (SHIP-BLOCKING)
---------------------------------
Every embedded row is rebuilt from an explicit whitelist.  The following never
enter the dashboard: full prompts/contracts, raw ``public_metadata`` dicts,
``model_input.text``, final answer text, verifier diagnostics, oracle/private
data, any ``*_ref``/workspace/path value, raw Pi events, host/model config and
task-level model posterior samples.  Allowed: IDs, family/template/version/
seed/difficulty, policy, split, verified success/failure code and verifier
IDs, usage counters, message/tool counts, final text length and *flattened*
finite numeric/bool public metadata (taken from ``model_input.public_metadata``
when present).  A prompt preview is allowed but is capped at
:data:`PROMPT_PREVIEW_LIMIT` characters.

Robustness
----------
The dataset is required: a missing file raises ``FileNotFoundError`` and a
malformed line raises ``ValueError`` with its path.  Rows that are unusable
(missing identity or label keys) are skipped and reported as warnings.  The
optional ``metrics`` and ``baselines`` inputs degrade to explicit
``missing``/``malformed`` states instead of crashing, and never embed raw
optional files (only whitelisted numeric aggregates).

Determinism
-----------
All iteration is explicitly sorted, no timestamps or randomness are embedded,
and JSON is serialized with ``sort_keys=True``.  Identical inputs therefore
produce byte-identical HTML.

Rendering model
---------------
The HTML contains a fully rendered *unfiltered* state generated by this module
(so the aggregate tables are testable in the static markup), plus an embedded
JSON payload.  The inline JavaScript mirrors these aggregation functions and
re-renders every row-derived section synchronously when the native checkboxes
in the filter bar change.  JS never uses ``innerHTML`` with untrusted values:
dynamic content is built with ``textContent``/``createElement``, and the
embedded JSON escapes ``<``/``>``/``&`` so ``</script>`` cannot break out.
"""

