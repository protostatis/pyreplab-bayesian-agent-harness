def aggregate_gym(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """Gym-health KPIs plus the family x policy success table."""
    total_rows = len(rows)
    task_ids = sorted({row["task_id"] for row in rows})
    total_tasks = len(task_ids)
    policies = sorted({row["policy_id"] for row in rows})
    families = sorted({row["family"] for row in rows})
    paired_tasks = 0
    for task_id in task_ids:
        present = {row["policy_id"] for row in rows if row["task_id"] == task_id}
        if len(present) >= 2:
            paired_tasks += 1
    success_count = sum(1 for row in rows if row["verified_success"])
    token_values = [total_tokens(row) for row in rows]
    cells: dict[tuple[str, str], dict[str, int]] = {}
    for row in rows:
        cell = cells.setdefault((row["family"], row["policy_id"]), {"n": 0, "success": 0})
        cell["n"] += 1
        cell["success"] += 1 if row["verified_success"] else 0
    family_policy: list[dict[str, Any]] = []
    for family in families:
        for policy in policies:
            cell = cells.get((family, policy))
            if cell is None:
                continue
            family_policy.append(
                {
                    "family": family,
                    "policy": policy,
                    "n": cell["n"],
                    "success": cell["success"],
                    "success_rate": (
                        cell["success"] / cell["n"] if cell["n"] else None
                    ),
                }
            )
    return {
        "total_rows": total_rows,
        "total_tasks": total_tasks,
        "paired_tasks": paired_tasks,
        "task_coverage": paired_tasks / total_tasks if total_tasks else None,
        "success_count": success_count,
        "overall_success_rate": success_count / total_rows if total_rows else None,
        "avg_total_tokens": _mean(token_values) if token_values else None,
        # Real paired-disagreement rate so the static Gym Health KPI is not "—".
        "disagreement_rate": policy_disagreement(rows)["disagreement_rate"],
        "policies": policies,
        "families": families,
        "family_policy": family_policy,
    }


def pair_policies(rows: list[dict[str, Any]]) -> tuple[str | None, str | None]:
    """The two policies compared in the disagreement matrix.

    The canonical experiment policies ``direct`` and ``deliberate`` map to
    slots A and B when present, matching the fixed direct=blue / deliberate=
    orange scheme.  Otherwise the two most frequent policies are used with ties
    broken deterministically by policy id.
    """
    counts = Counter(row["policy_id"] for row in rows)
    if not counts:
        return None, None
    ordered = sorted(counts.items(), key=lambda item: (-item[1], item[0]))
    available = [policy_id for policy_id, _count in ordered]
    policy_a = "direct" if "direct" in counts else available[0]
    if "deliberate" in counts and "deliberate" != policy_a:
        policy_b = "deliberate"
    else:
        rest = [policy_id for policy_id in available if policy_id != policy_a]
        policy_b = rest[0] if rest else None
    return policy_a, policy_b


def _task_policy_outcome(
    rows: list[dict[str, Any]], task_id: str | None, policy: str | None
) -> bool | None:
    """Representative outcome for one (task, policy): first attempt by id."""
    if task_id is None or policy is None:
        return None
    candidates = sorted(
        (
            row
            for row in rows
            if row["task_id"] == task_id and row["policy_id"] == policy
        ),
        key=lambda row: (row.get("attempt_id") or ""),
    )
    if not candidates:
        return None
    return bool(candidates[0]["verified_success"])


def policy_disagreement(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """Paired (same ``task_id``, two policies) 2x2 outcome analysis."""
    policy_a, policy_b = pair_policies(rows)
    task_ids = sorted({row["task_id"] for row in rows})
    total_tasks = len(task_ids)
    paired_tasks = 0
    unpaired_tasks = 0
    matrix = {"both_ok": 0, "a_only": 0, "b_only": 0, "both_fail": 0}
    by_family_counts: dict[str, dict[str, Any]] = {}
    for task_id in task_ids:
        present = {row["policy_id"] for row in rows if row["task_id"] == task_id}
        family = next(
            (row["family"] for row in rows if row["task_id"] == task_id),
            None,
        )
        if policy_a in present and policy_b in present:
            paired_tasks += 1
        else:
            unpaired_tasks += 1
            continue
        cell = by_family_counts.setdefault(
            family, {"paired": 0, "both_ok": 0, "a_only": 0, "b_only": 0, "both_fail": 0}
        )
        cell["paired"] += 1
        outcome_a = _task_policy_outcome(rows, task_id, policy_a)
        outcome_b = _task_policy_outcome(rows, task_id, policy_b)
        if outcome_a is None or outcome_b is None:
            continue
        if outcome_a and outcome_b:
            matrix["both_ok"] += 1
            cell["both_ok"] += 1
        elif outcome_a and not outcome_b:
            matrix["a_only"] += 1
            cell["a_only"] += 1
        elif not outcome_a and outcome_b:
            matrix["b_only"] += 1
            cell["b_only"] += 1
        else:
            matrix["both_fail"] += 1
            cell["both_fail"] += 1
    disagreement = matrix["a_only"] + matrix["b_only"]
    by_family: list[dict[str, Any]] = []
    for family in sorted(by_family_counts):
        cell = by_family_counts[family]
        cell = dict(cell)
        cell["family"] = family
        cell["disagreement"] = cell["a_only"] + cell["b_only"]
        cell["disagreement_rate"] = (
            cell["disagreement"] / cell["paired"] if cell["paired"] else None
        )
        by_family.append(cell)
    return {
        "policy_a": policy_a,
        "policy_b": policy_b,
        "matrix": matrix,
        "disagreement_count": disagreement,
        "disagreement_rate": disagreement / paired_tasks if paired_tasks else None,
        "paired_tasks": paired_tasks,
        "unpaired_tasks": unpaired_tasks,
        "total_tasks": total_tasks,
        "by_family": by_family,
    }


def failure_analysis(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """Failure counts and rates by task family and by failure code."""
    total_rows = len(rows)
    failures = [row for row in rows if not row["verified_success"]]
    failure_count = len(failures)
    by_family: dict[str, dict[str, int]] = {}
    by_code: Counter[str] = Counter()
    for row in rows:
        family = row["family"]
        cell = by_family.setdefault(family, {"total": 0, "failures": 0})
        cell["total"] += 1
        if not row["verified_success"]:
            cell["failures"] += 1
            if row.get("failure_code") is not None:
                by_code[row["failure_code"]] += 1
    family_rows: list[dict[str, Any]] = []
    for family in sorted(by_family):
        cell = by_family[family]
        family_rows.append(
            {
                "family": family,
                "total": cell["total"],
                "failures": cell["failures"],
                "failure_rate": (
                    cell["failures"] / cell["total"] if cell["total"] else None
                ),
            }
        )
    code_rows: list[dict[str, Any]] = []
    for code, count in sorted(by_code.items(), key=lambda item: (-item[1], item[0])):
        code_rows.append(
            {
                "code": code,
                "count": count,
                "share_of_failures": (
                    count / failure_count if failure_count else None
                ),
                "failure_rate": count / total_rows if total_rows else None,
            }
        )
    return {
        "total_rows": total_rows,
        "failure_count": failure_count,
        "failure_rate": failure_count / total_rows if total_rows else None,
        "by_family": family_rows,
        "by_code": code_rows,
    }


def cost_stats(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """Mean/std/min/max of tokens, tool calls and messages by family x policy."""
    groups: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for row in rows:
        groups.setdefault((row["family"], row["policy_id"]), []).append(row)
    out_rows: list[dict[str, Any]] = []
    for key in sorted(groups):
        family, policy = key
        members = groups[key]
        tokens = [float(total_tokens(row)) for row in members]
        tools = [float(row.get("tool_call_count") or 0) for row in members]
        messages = [float(row.get("assistant_message_count") or 0) for row in members]

        def _bundle(values: list[float]) -> dict[str, float | None]:
            lo, hi = _min_max(values)
            return {
                "mean": _mean(values),
                "std": _pop_std(values),
                "min": lo,
                "max": hi,
            }

        out_rows.append(
            {
                "family": family,
                "policy": policy,
                "n": len(members),
                "total_tokens": _bundle(tokens),
                "tool_calls": _bundle(tools),
                "assistant_messages": _bundle(messages),
            }
        )
    return {"rows": out_rows}


