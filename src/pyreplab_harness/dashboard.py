def _load_dataset_rows(dataset_path: str | Path) -> tuple[list[dict[str, Any]], int]:
    """Load deterministic JSONL rows, raising on missing file / bad JSON.

    Returns ``(rows, skipped)`` where ``skipped`` counts lines that were valid
    JSON but unusable (missing identity or label keys).  A malformed JSON line
    raises ``ValueError`` with the file path and line number.
    """
    path = Path(dataset_path).expanduser().resolve()
    if not path.is_file():
        raise FileNotFoundError(f"dataset does not exist: {path}")
    rows: list[dict[str, Any]] = []
    skipped = 0
    with path.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError as error:
                raise ValueError(f"malformed JSON at {path}:{line_number}: {error}") from error
            if not isinstance(row, dict):
                skipped += 1
                continue
            if not (
                isinstance(row.get("task_id"), str)
                and isinstance(row.get("policy_id"), str)
            ):
                skipped += 1
                continue
            label = row.get("verified_success")
            if label is True or label is False:
                pass
            elif label in (0, 1):
                row["verified_success"] = bool(label)
            else:
                skipped += 1
                continue
            rows.append(row)
    return rows, skipped


def _sanitize_usage(usage: Any) -> dict[str, int]:
    """Whitelisted usage counters: integer values only."""
    if not isinstance(usage, dict):
        return {}
    out: dict[str, int] = {}
    for key, value in usage.items():
        if isinstance(value, bool):
            continue
        if isinstance(value, int):
            out[str(key)] = value
        elif isinstance(value, float) and math.isfinite(value) and value.is_integer():
            out[str(key)] = int(value)
    return out


def _sanitize_metadata(row: dict[str, Any]) -> dict[str, Any]:
    """Flattened finite numeric/bool public metadata (never the raw dict)."""
    model_input = row.get("model_input")
    flat = None
    if isinstance(model_input, dict) and isinstance(model_input.get("public_metadata"), dict):
        flat = model_input["public_metadata"]
    else:
        raw = row.get("public_metadata")
        if isinstance(raw, dict):
            flat = flatten_public_metadata(raw)
    if not isinstance(flat, dict):
        return {}
    cleaned: dict[str, Any] = {}
    for key, value in flat.items():
        if isinstance(value, bool):
            cleaned[str(key)] = value
        elif isinstance(value, int):
            cleaned[str(key)] = value
        elif isinstance(value, float) and math.isfinite(value):
            cleaned[str(key)] = value
    return cleaned


def _row_to_public(row: dict[str, Any]) -> dict[str, Any]:
    """Rebuild one dataset row from an explicit whitelist of allowed fields.

    Every key written below is individually allowed.  Forbidden content
    (full prompt/contract, raw metadata, model_input.text, paths, diagnostics,
    events, host/model config, posterior samples) can therefore never leak:
    unknown keys are simply never copied.
    """
    return {
        "task_id": _s(row.get("task_id")),
        "family": _s(row.get("family")),
        "template_id": _s(row.get("template_id")),
        "generator_version": _s(row.get("generator_version")),
        "seed": _i(row.get("seed")),
        "difficulty": _s(row.get("difficulty")),
        "prompt_preview": _preview(row.get("prompt")),
        "attempt_id": _s(row.get("attempt_id")),
        "policy_id": _s(row.get("policy_id")),
        "policy_version": _s(row.get("policy_version")),
        "split": _s(row.get("split")),
        "verified_success": bool(row.get("verified_success")),
        "failure_code": _s(row.get("failure_code")),
        "verifier_id": _s(row.get("verifier_id")),
        "verifier_version": _s(row.get("verifier_version")),
        "usage": _sanitize_usage(row.get("usage")),
        "assistant_message_count": _i(row.get("assistant_message_count")),
        "tool_call_count": _i(row.get("tool_call_count")),
        "final_text_length": _i(row.get("final_text_length")),
        "metadata": _sanitize_metadata(row),
    }


def total_tokens(row: dict[str, Any]) -> int:
    """Total token counter for a public row (``usage.total_tokens`` or sum)."""
    usage = row.get("usage") or {}
    total = usage.get("total_tokens")
    if isinstance(total, int) and not isinstance(total, bool):
        return total
    if isinstance(total, float) and total.is_integer():
        return int(total)
    return sum(
        value
        for value in usage.values()
        if isinstance(value, int) and not isinstance(value, bool)
    )


